from enrich_lib import *


def calls(n):
    c = [1, 1]
    for i in range(2, n + 1):
        c.append(c[-1] + c[-2] + 1)
    return c[n]


def fib(n):
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


def sep(n):
    return "{:,}".format(n)


