def kdp2d(items, W):
    dp = [[0] * (W + 1)]
    for w, v in items:
        prev = dp[-1]
        dp.append([max(prev[j], prev[j - w] + v) if j >= w else prev[j] for j in range(W + 1)])
    return dp


