def fact_trace2(n):
    rows, ans = [], 1
    for i in range(1, n + 1):
        before = ans
        raw = before * i
        ans = raw % MOD
        rows.append([i, before, raw, ans, "হ্যাঁ" if raw >= MOD else "না"])
    return rows


