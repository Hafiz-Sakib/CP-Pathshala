# ───────────── phi 1..N ─────────────
def phi_sieve(n):
    phi = list(range(n + 1))
    snaps = [["শুরু (phi[i] = i)"] + phi[1:]]
    for p in range(2, n + 1):
        if phi[p] == p:
            for i in range(p, n + 1, p):
                phi[i] -= phi[i] // p
            snaps.append(["p = %d এর পর" % p] + phi[1:])
    return snaps


