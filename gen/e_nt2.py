# ───────────── SOD formula ─────────────
def sodf_trace(n):
    rows, ans, orig = [], 1, n
    for p in PR:
        if p * p > n:
            rows.append([p, "—", "—", ans, "%d > %d → break" % (p * p, n)])
            break
        if n % p == 0:
            pw = p
            while n % p == 0:
                pw *= p; n //= p
            val = (pw - 1) // (p - 1)
            ans *= val
            rows.append([p, pw, "(%d − 1) / (%d − 1) = %d" % (pw, p, val), ans, "ans এ গুণ"])
        else:
            rows.append([p, "—", "—", ans, "ভাগ যায় না"])
    if n > 1:
        ans *= (n + 1)
        rows.append(["শেষে", "—", "(%d + 1)" % n, ans, "বাকি prime %d" % n])
    return rows


