# ───────────── binary exponentiation ─────────────
def be_trace(b, p, mod=MOD):
    rows, ans = [], 1
    bb = b
    while p:
        bit = p & 1
        before_p = bin(p)[2:]
        if bit:
            ans = ans * bb % mod
        rows.append([before_p, bit, bb, ans])
        bb = bb * bb % mod
        p >>= 1
    return rows


