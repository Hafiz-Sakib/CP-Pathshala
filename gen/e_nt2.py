# ───────────── Euler phi ─────────────
def phi_trace(n):
    rows, ans, p = [], n, 2
    rows.append(["শুরু", "—", n, ans, "ans = n"])
    m = n
    while p * p <= m:
        if m % p == 0:
            ans = ans // p * (p - 1)
            while m % p == 0:
                m //= p
            rows.append([p, p * p, m, ans, "ans = ans / %d × %d" % (p, p - 1)])
        else:
            rows.append([p, p * p, m, ans, "ভাগ যায় না"])
        p += 1
    if m > 1:
        ans = ans // m * (m - 1)
        rows.append(["শেষে", "—", 1, ans, "বাকি prime %d: ans / %d × %d" % (m, m, m - 1)])
    return rows


