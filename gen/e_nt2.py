# ───────────── NOD ─────────────
def nod_trace(n):
    rows, ans = [], 1
    for p in PR:
        if p * p > n:
            rows.append([p, "—", "—", "—", ans, "%d × %d = %d > %d → break" % (p, p, p * p, n)])
            break
        if n % p == 0:
            e = 0
            before = n
            while n % p == 0:
                n //= p; e += 1
            ans *= e + 1
            rows.append([p, before, e, n, ans, "%d এর ঘাত %d → ×(%d+1)" % (p, e, e)])
        else:
            rows.append([p, n, 0, n, ans, "ভাগ যায় না"])
    if n > 1:
        ans *= 2
        rows.append(["শেষে", n, 1, 1, ans, "n = %d বাকি, prime, ঘাত 1 → ×2" % n])
    return rows


