# ───────────── SOD series ─────────────
def sod_trace(n):
    rows, ans = [], 1
    for p in PR:
        if p * p > n:
            rows.append([p, "—", "—", "—", "%d > %d → break" % (p * p, n)])
            break
        if n % p == 0:
            cur, pw = 1, 1
            seq = ["1"]
            while n % p == 0:
                pw *= p; cur += pw; n //= p
                seq.append(str(pw))
            ans *= cur
            rows.append([p, " + ".join(seq), cur, ans, "ans এ গুণ হলো"])
        else:
            rows.append([p, "—", "—", ans, "ভাগ যায় না"])
    if n > 1:
        ans *= (n + 1)
        rows.append(["শেষে", "1 + %d" % n, n + 1, ans, "বাকি prime %d → ×(%d+1)" % (n, n)])
    return rows


