# ───────────── cnt & sum ─────────────
def cs_trace(n):
    rows, cnt, s, i = [], 0, 0, 1
    while i * i <= n:
        if n % i == 0:
            cnt += 1; s += i
            note = "i = %d" % i
            if i != n // i:
                cnt += 1; s += n // i
                note += ", n/i = %d" % (n // i)
            else:
                note += " (n/i সমান, তাই আর যোগ না)"
            rows.append([i, n // i, cnt, s, note])
        else:
            rows.append([i, "—", cnt, s, "ভাগ যায় না"])
        i += 1
    return rows


