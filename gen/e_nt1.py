    ok = [True] * (n + 1)
    ok[0] = ok[1] = False
    rows = []
    snaps = {}
    for i in range(2, n + 1):
        crossed = [j for j in range(i + i, n + 1, i)]
        for j in crossed:
            ok[j] = False
        rows.append([i, ", ".join(map(str, crossed)) if crossed else "(কিছু নেই)", "prime" if ok[i] else "কাটা"])
        if i in (2, 3):
            snaps[i] = list(ok)
    return ok, rows, snaps


