def pf_sieve(n):
    rows = []
    for p in PR:
        if p * p > n:
            rows.append([p, p * p, n, "—", "%d > %d → break" % (p * p, n)])
            break
        if n % p == 0:
            while n % p == 0:
                rows.append([p, p * p, n, "%d %% %d = 0" % (n, p), "push %d, n = %d" % (p, n // p)])
