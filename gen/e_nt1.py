def sieve_bit(n):
    ok = [0] * (n + 2)
    for i in range(3, n + 1, 2):
        ok[i] = 1
    rows = []
    i = 3
    while i * i <= n:
        if ok[i]:
            cr = list(range(i * i, n + 1, i + i))
            for j in cr:
                ok[j] = 0
            rows.append([i, i * i, i + i, ", ".join(map(str, cr))])
        else:
            rows.append([i, i * i, "—", "(i prime না, তাই কিছু কাটলো না)"])
        i += 2
    ok[1] = 0
    ok[2] = 1
    return ok, rows


