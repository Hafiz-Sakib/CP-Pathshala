def prime_list(n):
    s = [True] * (n + 1)
    s[0:2] = [False, False]
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            for j in range(i * i, n + 1, i):
                s[j] = False
    return [i for i in range(n + 1) if s[i]]


PR = prime_list(1000)

# ───────────── Prime check ─────────────
def prime_trace(n):
    rows, i = [], 2
    while i * i <= n:
        r = n % i
        rows.append([i, i * i, "%d %% %d = %d" % (n, i, r), "ভাগ যায় → prime না ❌" if r == 0 else "যায় না, এগোও"])
        if r == 0:
            return rows, False
        i += 1
    rows.append([i, i * i, "—", "%d × %d = %d > %d, লুপ থামলো" % (i, i, i * i, n)])
    return rows, True


