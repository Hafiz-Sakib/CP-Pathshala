# ───────────── GCD ─────────────
def euclid(a, b):
    rows = []
    while b:
        rows.append([a, b, "%d %% %d = %d" % (a, b, a % b), "GCD(%d, %d)" % (b, a % b)])
        a, b = b, a % b
    rows.append([a, 0, "b = 0", "উত্তর = %d" % a])
    return rows


