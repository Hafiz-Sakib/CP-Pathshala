def pf_nosieve(n):
    rows, pf = [], []
    while n % 2 == 0:
        rows.append(["2 (প্রথমে আলাদা)", n, "%d %% 2 = 0" % n, 2, n // 2]); n //= 2; pf.append(2)
    i = 3
    while i <= math.sqrt(n):
        if n % i == 0:
            while n % i == 0:
                rows.append([i, n, "%d %% %d = 0" % (n, i), i, n // i]); n //= i; pf.append(i)
        else:
            rows.append([i, n, "%d %% %d = %d" % (n, i, n % i), "—", n])
        i += 2
    if n > 2:
        rows.append(["লুপ শেষ", n, "n > 2", n, 1]); pf.append(n)
    return rows, pf


